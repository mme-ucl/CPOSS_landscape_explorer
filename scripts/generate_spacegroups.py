#!/usr/bin/env python3
"""Generate an offline, versioned Hermann–Mauguin lookup (Gemmi 0.7.5)."""
import json
from importlib.metadata import distribution
from pathlib import Path
import re
import unicodedata

import gemmi

ROOT = Path(__file__).resolve().parents[1]


def key(text):
    text = unicodedata.normalize("NFKC", text).replace("−", "-")
    text = re.sub(r"([0-9])[\u0304\u0305]", r"-\1", text)
    return re.sub(r"[\s_]", "", text).lower()


def main():
    if gemmi.__version__ != "0.7.5":
        raise RuntimeError("Use Gemmi 0.7.5 to reproduce this versioned mapping")
    package = distribution("gemmi")
    license_file = next(item for item in package.files if str(item).endswith(".dist-info/licenses/LICENSE.txt"))
    (ROOT / "assets/spacegroups.LICENSE").write_text(package.locate_file(license_file).read_text())
    aliases = {}
    for group in gemmi.spacegroup_table():
        for name in [group.hm, group.xhm(), group.short_name()]:
            aliases.setdefault(key(name), set()).add(group.number)
    data = {
        "generator": "Gemmi " + gemmi.__version__,
        "source": "https://gemmi.readthedocs.io/en/stable/symmetry.html",
        "license": "MPL-2.0; generated from the Gemmi crystallographic space-group table",
        "symbols": {name: next(iter(numbers)) for name, numbers in sorted(aliases.items()) if len(numbers) == 1},
        "ambiguous": sorted(name for name, numbers in aliases.items() if len(numbers) != 1),
    }
    assert set(data["symbols"].values()) == set(range(1, 231))
    source = "/* Generated by scripts/generate_spacegroups.py; do not edit by hand. */\n"
    source += "(function(root){ const data = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    source += "if(typeof module==='object'&&module.exports) module.exports=data; else root.CpossSpaceGroups=data; })(globalThis);\n"
    (ROOT / "assets/spacegroups.js").write_text(source)
    print(f"Generated {len(data['symbols'])} validated symbols; {len(data['ambiguous'])} ambiguous keys")


if __name__ == "__main__":
    main()
